export function getStoriesFor(ageGroupId) {
  const ageIndex = {
    "1-3": 0,
    "4-6": 1,
    "7-10": 2
  };

  return ST[ageIndex[ageGroupId] ?? 1] ?? ST[1];
}

export function getStoryText(value, language = "en") {
  if (typeof value === "string") return value;

  if (value && typeof value === "object") {
    return value[language] || value.en || "";
  }

  return "";
}
